_HOSTILE = '<script>alert(1)</script>" onload="x R&D https://evil.example/a.js'


def _hostile_report() -> dict[str, Any]:
    report = sample_compare_report()
    report["target"] = report["run_id"] = report["git_sha"] = _HOSTILE
    agent = report["evals"][0]
    agent["subject"]["name"] = agent["subject"]["qualified_name"] = _HOSTILE
    agent["dataset"]["name"] = _HOSTILE
    agent["metrics"][1]["name"] = _HOSTILE
    agent["models"][0]["metrics"] = {_HOSTILE: scores(0.9, 0.8, 1.0, 1, 1)}
    agent["models"][1].update(model=_HOSTILE, alias=_HOSTILE, error=_HOSTILE, status="partial", run_names=[_HOSTILE])
    agent["verdict"].update(model=_HOSTILE, summary=_HOSTILE, pin_suggestion=_HOSTILE)
    agent["verdict"]["excluded"] = [{"model": _HOSTILE, "reason": _HOSTILE}]
    agent["notes"] = [_HOSTILE]
    for question in agent["questions"]:
        question["id"] = question["text"] = _HOSTILE
        question["results"][_HOSTILE] = {"passed": True, "score": 1.0, "reason": _HOSTILE, "route": None}
        question["changes"] = {_HOSTILE: "fixes"}
    profile = report["evals"][1]
    profile["questions"][0]["results"][SONNET]["route"] = [_HOSTILE]
    return report


def test_every_report_value_is_escaped_in_text_and_attributes() -> None:
    document = render_compare_html(_hostile_report())
    assert "<script" not in document.lower()
    assert "&lt;script&gt;alert(1)&lt;&#47;script&gt;" in document
    assert "R&amp;D" in document
    tree = _parse(document)
    names = {name for item in tree.elements for name in item.attrs}
    assert not [name for name in names if name.startswith("on")]
    assert [card.attrs["data-model"] for card in _with("data-winner", tree, "true")] == [_HOSTILE]
    assert _with("data-cell", tree, _HOSTILE)
    assert any(_HOSTILE in str(cell.attrs["title"]) for cell in _with("data-cell", tree))


@pytest.mark.parametrize("report", [sample_compare_report, _hostile_report], ids=["sample", "hostile"])
def test_the_document_loads_nothing_and_runs_nothing(report: Callable[[], dict[str, Any]]) -> None:
    document = render_compare_html(report())
    for forbidden in ("<script", "http://", "https://", "//", "src=", 'href="http', "url(", "@import"):
        assert forbidden not in document.lower(), forbidden
    assert not re.search(r"\son[a-z]+\s*=", document, re.IGNORECASE)


def _all_null_cost(report: dict[str, Any]) -> None:
    for item in report["evals"]:
        for model in item["models"]:
            model["cost"] = None
            model["latency_ms"] = model["tokens"] = None
    report["cost_read_at"] = None


def _failed_model(report: dict[str, Any]) -> None:
    report["evals"][0]["models"][2] = model_entry(
        HAIKU, rank=None, status="failed", error=None, metrics={}, run_names=[], version=None, alias=None
    )
    report["evals"][0]["models"].append(model_entry("mystery", status="exploded", lifecycle="beta", rank=None))


def _zero_questions(report: dict[str, Any]) -> None:
    report["evals"][0]["questions"] = []
    report["evals"][0]["dataset"]["questions"] = 0


def _single_model(report: dict[str, Any]) -> None:
    del report["evals"][1]
    report["evals"][0]["models"] = report["evals"][0]["models"][:1]
    report["evals"][0]["verdict"] = {"kind": "winner", "model": None, "summary": None, "excluded": [{}]}


def _incomplete(report: dict[str, Any]) -> None:
    report["evals"][0]["verdict"] = {"kind": "incomplete", "model": None, "summary": "The pinned model failed."}
    report["evals"][0]["metrics"] = [{"name": "answer_correctness", "gated": True, "threshold": None}]


def _no_gated_metric(report: dict[str, Any]) -> None:
    report["evals"][0]["metrics"] = [{"name": "logical_consistency", "gated": False, "threshold": None}]


def _odd_values(report: dict[str, Any]) -> None:
    report.update(target=None, run_id="  ", generated_at="yesterday", git_sha=True)
    agent = report["evals"][0]
    agent["kind"] = "robot"
    agent["subject"] = None
    agent["notes"] = "not a list"
    agent["metrics"].append("not an object")
    agent["models"][1]["rank"] = "first"
    agent["models"][1]["metrics"]["answer_correctness"] = {"mean": float("inf"), "min": None, "max": 1, "passed": None}
    agent["models"][0]["cost"]["agent_credits"] = {"state": "known", "value": None}
    agent["models"][0]["latency_ms"]["p95"] = 420
    question = agent["questions"][0]
    question["results"][SONNET].update(passed=None, reason=None)
    question["results"][OPUS] = {"passed": None, "score": None}
    question["changes"] = {SONNET: "fixes", OPUS: "worse"}
    profile = report["evals"][1]
    profile["questions"][0]["results"][SONNET]["route"] = "not a list"
    profile["verdict"] = None


def _nothing(report: dict[str, Any]) -> None:
    report["evals"] = [{}]
    report["generated_at"] = "2026-10-22T14:03:11"


def _no_evals(report: dict[str, Any]) -> None:
    report["evals"] = []


def _cheap_ties(report: dict[str, Any]) -> None:
    for model in report["evals"][0]["models"]:
        model["cost"]["credits_per_question"] = {"state": "known", "value": 0}
        model["metrics"]["answer_correctness"]["mean"] = 0.1
        model["metrics"]["answer_correctness"]["min"] = model["metrics"]["answer_correctness"]["max"] = 0.1
    report["evals"][1]["models"][0]["metrics"]["routing_accuracy"]["mean"] = 0.45
    report["evals"][1]["models"][1]["model"] = "a-model-name-far-too-long-to-fit-beside-its-bar"


