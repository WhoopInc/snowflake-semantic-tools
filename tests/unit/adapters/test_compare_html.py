_VOID = frozenset(("area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "wbr"))
_EVAL_SECTIONS = ("eval", "verdict", "scorecards", "metrics", "quality-cost", "questions", "cost", "notes")


@dataclass
class _Element:
    tag: str
    attrs: dict[str, str | None]
    text: list[str] = field(default_factory=list)

    @property
    def content(self) -> str:
        return "".join(self.text)


class _Tree(HTMLParser):
    """Every element of a document, in order, with the text inside it and any tag left unbalanced."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.elements: list[_Element] = []
        self.problems: list[str] = []
        self._open: list[_Element] = []

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        element = _Element(tag, dict(attrs))
        self.elements.append(element)
        if tag not in _VOID:
            self._open.append(element)

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        self.elements.append(_Element(tag, dict(attrs)))

    def handle_endtag(self, tag: str) -> None:
        if not self._open or self._open[-1].tag != tag:
            self.problems.append(f"</{tag}> closes {self._open[-1].tag if self._open else 'nothing'}")
            return
        self._open.pop()

    def handle_data(self, data: str) -> None:
        for element in self._open:
            element.text.append(data)

    def close(self) -> None:
        super().close()
        self.problems.extend(f"<{element.tag}> never closed" for element in self._open)


def _parse(document: str) -> _Tree:
    tree = _Tree()
    tree.feed(document)
    tree.close()
    assert not tree.problems, tree.problems
    return tree


def _with(attr: str, tree: _Tree, value: str | None = None) -> list[_Element]:
    return [item for item in tree.elements if attr in item.attrs and (value is None or item.attrs[attr] == value)]


def _render(report: dict[str, Any]) -> _Tree:
    return _parse(render_compare_html(report))


def _within(tree: _Tree, index: int) -> _Tree:
    """The elements of the `index`-th eval section only, as a tree of its own."""
    section = _with("data-section", tree, "eval")[index]
    start = tree.elements.index(section)
    after = _with("data-section", tree, "eval")[index + 1 :]
    stop = tree.elements.index(after[0]) if after else len(tree.elements)
    part = _Tree()
    part.elements = tree.elements[start:stop]
    return part


def test_the_sample_is_one_balanced_document_with_every_section() -> None:
    document = render_compare_html(sample_compare_report())
    assert document.startswith('<!doctype html>\n<html lang="en">')
    tree = _parse(document)
    assert [item.attrs["data-section"] for item in _with("data-section", tree, "header")] == ["header"]
    assert len(_with("data-section", tree, "footer")) == 1
    for key in _EVAL_SECTIONS:
        assert len(_with("data-section", tree, key)) == 2, key
    assert [item.attrs["href"] for item in tree.elements if item.tag == "a"] == ["#eval-1", "#eval-2"]
    footer = _with("data-section", tree, "footer")[0]
    assert footer.content == "Generated by SSTSchema sst.compare/1"


