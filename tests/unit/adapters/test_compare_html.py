def test_the_writer_writes_the_document_and_the_json_it_renders(tmp_path: Path) -> None:
    report = sample_compare_report()
    path = write_compare_report(tmp_path / "out" / "c7f2a19e", report)
    assert path == tmp_path / "out" / "c7f2a19e" / "report.html"
    assert path.read_text(encoding="utf-8") == render_compare_html(report)
    written = (path.parent / "compare.json").read_text(encoding="utf-8")
    assert json.loads(written) == report
    assert written.startswith('{\n  "schema": "sst.compare/1",\n  "generated_at"')


