"""Render a model comparison, an `sst.compare/1` report, as one self-contained HTML document.

`docs/design/compare-report-schema.md` is the input's contract. The document holds a header for
the run and one section per eval: the verdict, a scorecard per model, the metric and
quality-against-cost charts, the question heatmap, the cost table, and the method notes. It has
no script, no event handler, and no URL: styles are inline, charts inline SVG, and interactivity
is the browser's own (`<details>`, `title` tooltips, `:hover`). Every value read from the report
passes through `values.esc`; an enumeration picks a class from a fixed table, never from its text.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path

from snowflake_semantic_tools.adapters.paths import write_within
from snowflake_semantic_tools.adapters.report.compare_charts import metric_chart, quality_cost_chart
from snowflake_semantic_tools.adapters.report.compare_model import SCHEMA, EvalView, ModelRow, check_schema, read_evals
from snowflake_semantic_tools.adapters.report.compare_style import STYLE
from snowflake_semantic_tools.adapters.report.compare_tables import cost_table, question_heatmap
from snowflake_semantic_tools.adapters.report.values import (
    MISSING,
    credits,
    duration,
    esc,
    pill,
    score,
    text,
    timestamp,
)

REPORT_FILE = "report.html"
JSON_FILE = "compare.json"

_KINDS = {"agent": "Agent", "cowork_profile": "CoWork profile", "unknown": "Unknown subject"}
_VERDICTS = {
    "winner": ("★", "Winner"),
    "pinned_holds": ("✓", "Pinned model holds"),
    "no_clear_winner": ("≈", "No clear winner"),
    "incomplete": ("⚠", "Incomplete"),
    "unknown": ("?", "No verdict"),
}
_LIFECYCLES = {
    "ga": ("b-ga", "GA"),
    "preview": ("b-flag", "⚠ Preview"),
    "internal": ("b-flag", "⚠ Internal"),
    "deprecated": ("b-bad", "⚠ Deprecated"),
    "unknown": ("b-flag", "? Lifecycle unknown"),
}
_STATUSES = {
    "partial": ("◐ Partial", "some runs failed"),
    "failed": ("✗ Failed", "no run scored"),
    "unknown": ("? Status unknown", "the report does not say how the runs went"),
}
# Header terms whose values are long, and those that are identifiers, by their constant labels.
_WIDE = frozenset(("Qualified name", "Dataset", "Generated", "Cost read"))
_MONO = frozenset(("Qualified name", "Run", "Git SHA", "Released version"))
_WIDE_TERM = ' class="wide"'
_MONO_TERM = ' class="mono"'


def render_compare_html(report: Mapping[str, object]) -> str:
    """Return the HTML document for a parsed `sst.compare/1` report.

    Any value the schema allows to be null, and any that is missing or of the wrong type, renders
    as unknown rather than failing.

    Raises:
        ValueError: `report` does not carry the schema tag ``sst.compare/1``.
    """
    check_schema(report)
    views = read_evals(report)
    target, run_id = text(report.get("target")), text(report.get("run_id"))
    title = " · ".join(part for part in ("Model comparison", target, run_id) if part)
    toc = ""
    if len(views) > 1:
        links = "".join(
            f'<li><a href="#eval-{index}">{esc(_name(view))}</a></li>' for index, view in enumerate(views, 1)
        )
        toc = f'<nav aria-label="Evals"><ul class="toc">{links}</ul></nav>'
    sections = "".join(_eval_section(index, view) for index, view in enumerate(views, 1))
    if not views:
        sections = '<p class="empty" data-section="no-evals">The report holds no eval.</p>'
    return (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f'<meta name="color-scheme" content="light dark"><title>{esc(title)}</title><style>{STYLE}</style></head>'
        f"<body><main>{_page_header(report)}{toc}{sections}</main>"
        f'<footer class="foot" data-section="footer"><span>Generated by SST</span><span>Schema {SCHEMA}</span></footer>'
        "</body></html>\n"
    )


def write_compare_report(directory: Path, report: Mapping[str, object]) -> Path:
    """Write `report` as ``compare.json`` and its rendering as ``report.html`` in `directory`.

    The folder is created when missing, and each file is replaced in one rename. The JSON is
    written first, so a document on disk always has its data beside it.

    Returns:
        The path of ``report.html``.

    Raises:
        ValueError: `report` does not carry the schema tag ``sst.compare/1``; nothing is written.
        OSError: a file cannot be written (`UnsafeWrite` when a link or a non-file is in the way).
    """
    document = render_compare_html(report)
    write_within(directory, directory / JSON_FILE, json.dumps(dict(report), indent=2, sort_keys=False) + "\n")
    path = directory / REPORT_FILE
    write_within(directory, path, document)
    return path


def _page_header(report: Mapping[str, object]) -> str:
    fields = (
        ("Target", text(report.get("target"))),
        ("Run", text(report.get("run_id"))),
        ("Git SHA", text(report.get("git_sha"))),
        ("Generated", timestamp(report.get("generated_at"))),
        ("Cost read", timestamp(report.get("cost_read_at")) or "not read yet"),
    )
    return (
        '<header class="page-head" data-section="header"><div><p class="eyebrow">SST evals</p>'
        f'<h1>Model comparison</h1></div><dl class="meta">{_terms(fields)}</dl></header>'
    )


def _terms(fields: tuple[tuple[str, str | None], ...]) -> str:
    return "".join(
        f"<div{_WIDE_TERM if label in _WIDE else ''}><dt>{label}</dt>"
        f"<dd{_MONO_TERM if label in _MONO else ''}>{esc(value) if value else MISSING}</dd></div>"
        for label, value in fields
    )


def _name(view: EvalView) -> str:
    return view.subject["name"] or view.eval or "Unnamed eval"


def _eval_section(index: int, view: EvalView) -> str:
    """Render one eval: its header, then each block in reading order, every block id-stamped."""
    anchor = f"eval-{index}"
    dataset = " ".join(part for part in (view.dataset_name, view.dataset_version) if part) or None
    fields = (
        ("Qualified name", view.subject["qualified_name"]),
        ("Released version", view.subject["released_version"]),
        ("Pinned model", view.subject["pinned_model"]),
        ("Dataset", dataset),
        ("Questions", text(view.questions_count)),
        ("Runs per model", text(view.runs_per_model)),
    )
    headline = view.headline
    blocks = (
        ("scorecards", "Scorecards", "pinned first, then by rank", _scorecards(view)),
        ("metrics", "Metrics", "mean per model, whiskers show the spread of run means", _metrics(view)),
        ("quality-cost", "Quality against cost", headline.name if headline else "", _card(quality_cost_chart(view))),
        ("questions", "Questions", "result on the headline metric, by model", question_heatmap(view)),
        ("cost", "Cost", "per model, over every run", cost_table(view)),
    )
    body = "".join(_block(anchor, *block) for block in blocks)
    return (
        f'<section class="eval" id="{anchor}" data-section="eval" aria-labelledby="{anchor}-title">'
        f'<header><div class="title-row"><h2 id="{anchor}-title">{esc(_name(view))}</h2>'
        f'<span class="badge b-kind">{_KINDS[view.kind]}</span></div><dl class="meta">{_terms(fields)}</dl></header>'
        f"{_verdict(anchor, view)}{body}{_notes(view)}</section>"
    )


def _card(body: str) -> str:
    return f'<div class="card chart">{body}</div>'


def _block(anchor: str, key: str, title: str, aside: str, body: str) -> str:
    heading = f"{anchor}-{key}"
    return (
        f'<section class="block" data-section="{key}" aria-labelledby="{heading}">'
        f'<h3 id="{heading}">{title} <span class="muted">{esc(aside)}</span></h3>{body}</section>'
    )


def _verdict(anchor: str, view: EvalView) -> str:
    """Render the verdict banner: its kind, summary, pin suggestion, and the models left out."""
    verdict = view.verdict
    icon, label = _VERDICTS[verdict.kind]
    if verdict.kind == "winner" and verdict.model:
        label = f"{label} · {esc(verdict.model)}"
    summary = esc(verdict.summary) if verdict.summary else "The report gives no summary."
    extra = []
    if verdict.pin_suggestion:
        extra.append(
            f'<pre class="pin"><code>{esc(verdict.pin_suggestion)}</code></pre>'
            '<p class="hint">Review the line, then apply it through <code>sst apply</code>.</p>'
        )
    if verdict.excluded:
        items = "".join(
            f"<li>{esc(model) if model else 'Unnamed model'} — {esc(reason) if reason else 'no reason given'}</li>"
            for model, reason in verdict.excluded
        )
        extra.append(f'<p class="hint">Left out of the verdict:</p><ul class="excluded">{items}</ul>')
    more = f'<div class="extra">{"".join(extra)}</div>' if extra else ""
    return (
        f'<section class="card verdict v-{verdict.kind} block" data-section="verdict" data-verdict="{verdict.kind}" '
        f'aria-labelledby="{anchor}-verdict"><div class="icon" aria-hidden="true">{icon}</div>'
        f'<h3 class="label" id="{anchor}-verdict"><span class="sr">Verdict: </span>{label}</h3>'
        f'<p class="summary">{summary}</p>{more}</section>'
    )


def _scorecards(view: EvalView) -> str:
    if not view.models:
        return '<p class="empty">The report holds no model for this eval.</p>'
    winner = view.verdict.model if view.verdict.kind == "winner" else None
    return f'<div class="cards">{"".join(_scorecard(view, model, model.name == winner) for model in view.models)}</div>'


def _scorecard(view: EvalView, model: ModelRow, winner: bool) -> str:
    """Render one model's card: badges, headline mean and spread, cost, latency, identity, status."""
    css = "card scorecard" + (" is-pinned" if model.pinned else "") + (" is-winner" if winner else "")
    lifecycle_css, lifecycle = _LIFECYCLES[model.lifecycle]
    badges = [
        '<span class="badge b-pinned">Pinned</span>'
        if model.pinned
        else '<span class="badge b-candidate">Candidate</span>',
        f'<span class="badge {lifecycle_css}">{lifecycle}</span>',
    ]
    if model.rank is not None:
        badges.append(f'<span class="badge b-rank">Rank {esc(model.rank)}</span>')
    cost = model.costs["credits_per_question"]
    stats = (
        ("Credits / question", pill(cost.state, cost.state) if cost.value is None else esc(credits(cost.value))),
        ("p95 latency", MISSING if model.latency_p95 is None else esc(duration(model.latency_p95))),
    )
    stat_html = "".join(f"<div><dt>{label}</dt><dd>{value}</dd></div>" for label, value in stats)
    ident = " · ".join(
        f"{label} {esc(value)}" for label, value in (("version", model.version), ("alias", model.alias)) if value
    )
    ribbon = '<div class="ribbon" aria-hidden="true">Winner</div><span class="sr">Winner. </span>' if winner else ""
    return (
        f'<article class="{css}" data-model="{esc(model.name)}" data-winner="{str(winner).lower()}">{ribbon}'
        f'<h4>{esc(model.name)}</h4><div class="badges">{"".join(badges)}</div>{_headline(view, model)}'
        f'<dl class="stats">{stat_html}</dl><div class="ident">{ident or "version not recorded"}</div>'
        f"{_status(model)}</article>"
    )


def _headline(view: EvalView, model: ModelRow) -> str:
    """Render the card's big number, the headline metric's mean, with its spread and pass count."""
    metric = view.headline
    found = model.scores.get(metric.name) if metric else None
    caption = [metric.name + " mean" if metric else "no metric"]
    if found and found.low is not None and found.high is not None:
        caption.append(f"range {score(found.low)}–{score(found.high)}")
    if found and found.passed is not None and found.total is not None:
        caption.append(f"{text(found.passed)}/{text(found.total)} passed")
    big = score(found.mean if found else None)
    return (
        f'<div class="headline"><div class="big">{esc(big)}</div>'
        f'<div class="caption">{esc(" · ".join(caption))}</div></div>'
    )


def _status(model: ModelRow) -> str:
    if model.status == "completed":
        return ""
    label, meaning = _STATUSES[model.status]
    error = f'<span class="err">{esc(model.error)}</span>' if model.error else ""
    return f'<div class="status s-{model.status}" data-status="{model.status}">{label}: {meaning}.{error}</div>'


def _metrics(view: EvalView) -> str:
    if not view.metrics:
        return '<p class="empty">The report names no metric for this eval.</p>'
    charts = []
    for metric in view.gated_first:
        if metric.gated:
            gate = "gated" if metric.threshold is None else f"gated ≥ {esc(score(metric.threshold))}"
            badge = f'<span class="badge b-kind">{gate}</span>'
        else:
            badge = '<span class="badge b-candidate">reported, not gated</span>'
        charts.append(
            f'<figure class="card chart" data-metric="{esc(metric.name)}">'
            f"<h4>{esc(metric.name)} {badge}</h4>{metric_chart(metric, view.models)}</figure>"
        )
    return f'<div class="charts">{"".join(charts)}</div>'


def _notes(view: EvalView) -> str:
    notes = "".join(f"<li>{esc(note)}</li>" for note in view.notes) or "<li>The report holds no note.</li>"
    runs = "".join(f"<dt>{esc(model.name)}</dt><dd>{_run_names(model)}</dd>" for model in view.models)
    return (
        '<section class="block" data-section="notes"><details class="card notes"><summary>Method notes</summary>'
        f'<ul>{notes}</ul><h4>Snowsight runs</h4><dl class="runs">{runs or "<dd>—</dd>"}</dl></details></section>'
    )


def _run_names(model: ModelRow) -> str:
    return "".join(f"<code>{esc(run)}</code>" for run in model.run_names) or MISSING
