def _placed(block: str, noun: str) -> dict[str, Ui]:
    """The entries of where a routed block's objects are created: their database and schema."""
    return {f"{block}.+database": Ui(f"{noun} database"), f"{block}.+schema": Ui(f"{noun} schema")}


def _route(block: str) -> dict[str, Ui]:
    return {f"{block}.<route>": Ui("Folder route")}


def _bundle(block: str, noun: str) -> dict[str, Ui]:
    """The entries of a block whose objects publish as extension versions from a stage."""
    return {
        f"{block}.+bundle_stage": Ui("Bundle stage"),
        f"{block}.+certified": Ui(f"Certify each new {noun} version"),
        f"{block}.+version_prefix": Ui("Version alias prefix", advanced=True),
    }


